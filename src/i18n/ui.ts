/** French puts a narrow no-break space before ? ! ; and a no-break space before : and inside « ». */
export const frenchSpaces = (s: string) =>
  s.replace(/ ([?!;])/g, "\u202f$1").replace(/ :(?=\s|$)/g, "\u00a0:").replace(/« /g, "«\u00a0").replace(/ »/g, "\u00a0»");


