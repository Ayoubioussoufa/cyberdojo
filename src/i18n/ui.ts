/**
 * Every interface string, English and French side by side, so neither can be
 * missing: each entry is a pair, [English, French]. "{name}" is a slot filled
 * by fill(); "one|many" is a plural picked by plural(). French text is written
 * with plain spaces: the right no-break spaces before ? ! ; : are added below.
 * Course content (lessons, modules…) isn't here: it lives in content/fr/.
 */
import type { Lang } from "./lang";

