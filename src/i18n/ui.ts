type Table = typeof TABLE;
/** Both languages side by side, for scripts/check-i18n.ts. */
export const UI_TABLE: Table = TABLE;
export type Dict = { [NS in keyof Table]: { [K in keyof Table[NS]]: string } };

function pick(lang: Lang): Dict {
  const i = lang === "fr" ? 1 : 0;
  const out: Record<string, Record<string, string>> = {};
  for (const [ns, entries] of Object.entries(TABLE)) {
    out[ns] = {};
    for (const [k, pair] of Object.entries(entries as Record<string, Pair>)) out[ns][k] = i ? frenchSpaces(pair[1]) : pair[0];
  }
  return out as Dict;
}

