/** Every CSS variable the choices set, as name and checked #rrggbb value. Empty for the defaults. */
export function cssVars(p: Prefs): Record<string, string> {
  const out: Record<string, string> = {};
  for (const theme of ["dark", "light"] as const) {
    const c = p[theme];
    const e = effective(theme, c);
    if (c.bg) out[`--u-bg-${theme}`] = c.bg;
    if (c.surface) out[`--u-surface-${theme}`] = c.surface;
    if (c.accent) {
      out[`--u-accent-${theme}`] = c.accent;
      out[`--u-accent-ink-${theme}`] = e.accentInk;
      out[`--u-accent-soft-${theme}`] = e.accentSoft;
    }
  }
  return out;
}

/** Adds the texture stylesheet once. It's a file of this site, so the CSP's style-src 'self' allows it. */
export function loadTextures() {
  if (document.getElementById("tex-css")) return;
  const link = document.createElement("link");
  link.id = "tex-css";
  link.rel = "stylesheet";
  link.href = TEXTURE_CSS;
  document.head.appendChild(link);
}

/** The variable names the settings may set, and nothing else. */
export const VAR_NAME = /^--u-(bg|surface|accent|accent-ink|accent-soft)-(dark|light)$/;

/** Puts the settings on the page. Only validated values reach here, and none as CSS text. */
export function applyPrefs(p: Prefs, root: HTMLElement = document.documentElement) {
  if (p.font === DEFAULT_PREFS.font) delete root.dataset.font;
  else root.dataset.font = p.font;
  if (p.code === DEFAULT_PREFS.code) delete root.dataset.codeFont;
  else root.dataset.codeFont = p.code;
  if (p.texture === "none") delete root.dataset.texture;
  else {
    loadTextures();
    root.dataset.texture = p.texture;
  }
  for (const theme of ["dark", "light"]) for (const k of ["bg", "surface", "accent", "accent-ink", "accent-soft"]) root.style.removeProperty(`--u-${k}-${theme}`);
  for (const [name, value] of Object.entries(cssVars(p))) if (VAR_NAME.test(name) && HEX.test(value)) root.style.setProperty(name, value);
}

export function readLocal(): Prefs | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const r = cleanPrefs(JSON.parse(raw));
    return "prefs" in r ? r.prefs : null;
  } catch {
    return null;
  }
}

export function writeLocal(p: Prefs) {
  try {
    // The CSS variables travel with the settings, so the pre-paint script only has to copy them.
    localStorage.setItem(STORAGE_KEY, JSON.stringify({ ...p, vars: cssVars(p) }));
  } catch {
    // No storage: the settings still apply now, and come back from the account next time.
  }
}

