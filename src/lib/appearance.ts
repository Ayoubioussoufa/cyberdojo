/** How much of a chosen accent tints the page behind selected items, as CSS color-mix() would in sRGB. */
const SOFT_SHARE = 0.18;

const HEX = /^#[0-9a-f]{6}$/;
export const STORAGE_KEY = "cyberdojo-appearance";

function luminance(hex: string): number {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * (c[0] as number) + 0.7152 * (c[1] as number) + 0.0722 * (c[2] as number);
}

/** WCAG contrast ratio between two #rrggbb colours, from 1 to 21. */
export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

const toHex = (n: number) => Math.round(Math.min(255, Math.max(0, n))).toString(16).padStart(2, "0");
/** `share` of colour a over colour b, channel by channel. */
export function mix(a: string, b: string, share: number): string {
  return `#${[1, 3, 5].map((i) => toHex(parseInt(a.slice(i, i + 2), 16) * share + parseInt(b.slice(i, i + 2), 16) * (1 - share))).join("")}`;
}

/** Text on an accent button: near-black or white, whichever reads better on it. */
export const inkOn = (accent: string) => (contrast("#111111", accent) >= contrast("#ffffff", accent) ? "#111111" : "#ffffff");

/** Every colour a theme ends up drawing with, from the choices and the theme's defaults. */
export function effective(theme: Theme, c: Colours) {
  const d = THEME_DEFAULTS[theme];
  const bg = c.bg ?? d.bg;
  const accent = c.accent ?? d.accent;
  return {
    bg,
    surface: c.surface ?? d.surface,
    accent,
    accentInk: c.accent ? inkOn(c.accent) : d.accentInk,
    accentSoft: c.accent ? mix(c.accent, bg, SOFT_SHARE) : d.accentSoft,
  };
}

/**
 * Null when a theme's colours work together, otherwise what wouldn't be readable:
 * text on both backgrounds, the accent against both, the text on accent buttons,
 * and the accent on its own soft tint (selected items).
 */
export function unreadable(theme: Theme, c: Colours): string | null {
  const e = effective(theme, c);
  for (const t of THEME_TEXT[theme]) {
    if (contrast(t.colour, e.bg) < t.min || contrast(t.colour, e.surface) < t.min) return t.name;
  }
  if (contrast(e.accent, e.bg) < 3 || contrast(e.accent, e.surface) < 3) return "accent";
  if (contrast(e.accentInk, e.accent) < 4.5) return "accent-ink";
  if (contrast(e.accent, e.accentSoft) < 3) return "accent-soft";
  return null;
}

const hex = (v: unknown): string | null | undefined => {
  if (v === null || v === undefined || v === "") return null;
  if (typeof v !== "string") return undefined;
  const s = v.trim().toLowerCase();
  return HEX.test(s) ? s : undefined;
};

/**
 * Checks settings from anywhere: the browser's copy, a request, the database.
 * Returns the cleaned settings, or the reason they were refused.
 */
export function cleanPrefs(input: unknown): { prefs: Prefs } | { problem: string } {
  if (typeof input !== "object" || input === null || Array.isArray(input)) return { problem: "bad" };
  const o = input as Record<string, unknown>;
  const font = o.font ?? DEFAULT_PREFS.font;
  const code = o.code ?? DEFAULT_PREFS.code;
  if (!FONTS.some((f) => f.id === font) || !CODE_FONTS.some((f) => f.id === code)) return { problem: "font" };
  const texture = o.texture ?? DEFAULT_PREFS.texture;
  if (!TEXTURES.some((t) => t.id === texture)) return { problem: "bad" };
  const out: Prefs = { font: font as FontId, code: code as CodeFontId, texture: texture as TextureId, dark: { bg: null, surface: null, accent: null }, light: { bg: null, surface: null, accent: null } };
  for (const theme of ["dark", "light"] as const) {
    const c = o[theme];
    if (c === undefined || c === null) continue;
    if (typeof c !== "object" || Array.isArray(c)) return { problem: "bad" };
    for (const key of KEYS) {
      const v = hex((c as Record<string, unknown>)[key]);
      if (v === undefined) return { problem: "colour" };
      out[theme][key] = v;
    }
    if (unreadable(theme, out[theme])) return { problem: "contrast" };
  }
  return { prefs: out };
}

/** #rrggbb from hue (degrees), saturation and lightness (0 to 1). */
export function hsl(h: number, sat: number, light: number): string {
  const a = sat * Math.min(light, 1 - light);
  const f = (n: number) => {
    const k = (n + h / 30) % 12;
    return light - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
  };
  return `#${[f(0), f(8), f(4)].map((v) => toHex(v * 255)).join("")}`;
}

/** Where the accent's hue sits relative to the background's, per colour-harmony rule. */
const HARMONIES: Record<string, number[]> = {
  analogous: [30, -30],
  complementary: [180],
  triadic: [120, 240],
  split: [150, 210],
};

/**
 * A fresh palette for one theme, different on every call: a random hue for the
 * backgrounds, an accent placed by a random harmony rule, and lightness kept in
 * the band each theme needs. Only a palette that passes every readability check
 * is returned; after 200 tries (practically never) it falls back to the defaults.
 */
export function randomPalette(theme: Theme, rand: () => number = Math.random): Colours & { harmony: string } {
  const pick = <T,>(list: readonly T[]) => list[Math.floor(rand() * list.length)] as T;
  for (let i = 0; i < 200; i++) {
    const harmony = pick(Object.keys(HARMONIES));
    const h = rand() * 360;
    const sat = 0.12 + rand() * 0.3;
    const accentHue = (h + pick(HARMONIES[harmony] as number[]) + 360) % 360;
    const c: Colours =
      theme === "dark"
        ? { bg: hsl(h, sat, 0.06 + rand() * 0.05), surface: hsl(h, sat, 0.11 + rand() * 0.04), accent: hsl(accentHue, 0.55 + rand() * 0.35, 0.55 + rand() * 0.15) }
        : { bg: hsl(h, sat, 0.92 + rand() * 0.04), surface: hsl(h, sat * 0.6, 0.97 + rand() * 0.02), accent: hsl(accentHue, 0.6 + rand() * 0.35, 0.26 + rand() * 0.12) };
    if (!unreadable(theme, c)) return { ...c, harmony };
  }
  return { bg: null, surface: null, accent: null, harmony: "none" };
}

