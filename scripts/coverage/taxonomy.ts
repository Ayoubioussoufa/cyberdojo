/**
 * The field, written down independently of what the course happens to contain.
 *
 * Baselines: the 21 CyBOK v1.1 knowledge areas, OWASP Top 10:2025, the 2025 CWE
 * Top 25, the 15 Enterprise ATT&CK tactics (v20), and the twelve domains in the
 * brief. Each topic is one regex, so `pnpm audit:coverage` can look for it in
 * every surface of the course and show its evidence.
 *
 * A topic that is shallow in the course is split here into a basic row and an
 * advanced row, so depth gaps show up as gaps rather than hiding behind a hit
 * count on the basic word.
 *
 * review.ts corrects the automatic verdicts, with a reason for each.
 */
export type Verdict = "present" | "partial" | "missing";

export interface Topic {
  label: string;
  re: RegExp;
  tool?: boolean;
}
export interface Group {
  name: string;
  topics: Topic[];
}
export interface Domain {
  id: string;
  title: string;
  basis: string;
  groups: Group[];
}

const T = (label: string, re: RegExp): Topic => ({ label, re });
const K = (label: string, re: RegExp): Topic => ({ label, re, tool: true });
const G = (name: string, ...topics: Topic[]): Group => ({ name, topics });

